#!/usr/bin/env bash
# Sole-committer invariant.
#
# Fails unless every audited commit has author == committer ==
#   mikeZ98 <145975972+mikeZ98@users.noreply.github.com>
# and its message carries zero git trailers (no Co-authored-by, no Signed-off-by,
# nothing) and no automated tool signature. Unless --history-only is given, it also
# refuses a git identity configuration or environment that would violate the
# invariant on the next commit.
#
# Usage:
#   sh scripts/audit_identity.sh                        # identity config + every ref
#   sh scripts/audit_identity.sh --msg-file FILE        # also audit a pending message
#   sh scripts/audit_identity.sh --history-only --rev HEAD
#       CI mode: skip the local identity (a runner never commits) and audit exactly
#       the history reachable from the commit under test.

# Re-exec under real bash when launched via `sh` (POSIX mode lacks process
# substitution and ${!name} indirection).
if [ -z "${BASH_VERSION:-}" ] || shopt -qo posix 2>/dev/null; then exec bash "$0" "$@"; fi
set -euo pipefail

readonly EXPECTED_NAME="mikeZ98"
readonly EXPECTED_EMAIL="145975972+mikeZ98@users.noreply.github.com"
readonly EXPECTED="${EXPECTED_NAME} <${EXPECTED_EMAIL}>"
# Automated tool signatures and attribution markers, matched case-insensitively.
# The robot emoji is spliced in as raw UTF-8 bytes: ERE has no \x escapes.
readonly SIGNATURE_RE='generated with \[|generated by|noreply@anthropic\.com|co-authored-by|'$'\xf0\x9f\xa4\x96'

msg_file=""
history_only=0
rev="--all"
while (($#)); do
  case "$1" in
    --msg-file) msg_file="${2:?--msg-file needs a path}"; shift 2 ;;
    --history-only) history_only=1; shift ;;
    --rev) rev="${2:?--rev needs a revision}"; shift 2 ;;
    -h | --help) sed -n '2,16p' "$0"; exit 0 ;;
    *) printf 'audit_identity.sh: unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done

cd "$(git rev-parse --show-toplevel)"

failures=0
fail() {
  printf '  \xe2\x9c\x97 %s\n' "$1" >&2
  failures=$((failures + 1))
}

audit_message() {
  local label="$1" body="$2" trailers
  if grep -qiE "${SIGNATURE_RE}" <<<"${body}"; then
    fail "${label} carries an attribution or tool signature"
  fi
  trailers="$(git interpret-trailers --parse <<<"${body}")"
  [[ -z "${trailers}" ]] || fail "${label} carries trailers: ${trailers//$'\n'/; }"
}

# ---------------------------------------------------------------- next-commit identity
if ((history_only)); then
  printf '  - local identity skipped (--history-only)\n'
else
  for var in GIT_AUTHOR_NAME GIT_COMMITTER_NAME; do
    value="${!var:-}"
    if [[ -n "${value}" && "${value}" != "${EXPECTED_NAME}" ]]; then
      fail "environment ${var}='${value}' overrides the sole committer"
    fi
  done
  for var in GIT_AUTHOR_EMAIL GIT_COMMITTER_EMAIL; do
    value="${!var:-}"
    if [[ -n "${value}" && "${value}" != "${EXPECTED_EMAIL}" ]]; then
      fail "environment ${var}='${value}' overrides the sole committer"
    fi
  done
  configured_name="$(git config --get user.name || true)"
  configured_email="$(git config --get user.email || true)"
  if [[ "${configured_name}" != "${EXPECTED_NAME}" || "${configured_email}" != "${EXPECTED_EMAIL}" ]]; then
    fail "git config identity is '${configured_name} <${configured_email}>', expected '${EXPECTED}'"
  fi
fi

# ---------------------------------------------------------------- pending message
if [[ -n "${msg_file}" ]]; then
  [[ -f "${msg_file}" ]] || { printf 'audit_identity.sh: no such file: %s\n' "${msg_file}" >&2; exit 2; }
  audit_message "pending message" "$(git stripspace --strip-comments <"${msg_file}")"
fi

# ---------------------------------------------------------------- history
total=0
if git rev-parse --verify --quiet HEAD >/dev/null; then
  # Raw %an/%ae/%cn/%ce: .mailmap must not be able to launder an identity.
  while IFS=$'\x1f' read -r sha author_name author_email committer_name committer_email; do
    total=$((total + 1))
    short="${sha:0:12}"
    if [[ "${author_name}" != "${EXPECTED_NAME}" || "${author_email}" != "${EXPECTED_EMAIL}" ]]; then
      fail "${short} author is '${author_name} <${author_email}>'"
    fi
    if [[ "${committer_name}" != "${EXPECTED_NAME}" || "${committer_email}" != "${EXPECTED_EMAIL}" ]]; then
      fail "${short} committer is '${committer_name} <${committer_email}>'"
    fi
    audit_message "${short}" "$(git log -1 --format=%B "${sha}")"
  done < <(git log "${rev}" --format='%H%x1f%an%x1f%ae%x1f%cn%x1f%ce')
  ((total > 0)) || fail "no commits reachable from ${rev}"
fi

if ((failures > 0)); then
  printf 'audit_identity: FAILED (%d violation(s) across %d commit(s))\n' "${failures}" "${total}" >&2
  exit 1
fi
printf 'audit_identity: OK (%d commit(s) from %s, sole committer %s, zero trailers)\n' \
  "${total}" "${rev}" "${EXPECTED}"
